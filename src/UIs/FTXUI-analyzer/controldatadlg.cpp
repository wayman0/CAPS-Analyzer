{
}

void controlDataDialog::setControlType()
{
}

void controlDataDialog::setOperation()
{
}

bool controlDataDialog::confirm()
{
	return true;
}

void controlDataDialog::buildControlData(FILETYPE f, bool b)
{
	successFunc(f, b);
}

void controlDataDialog::dataCreationCancelled()
{
	cancelFunc();
}

