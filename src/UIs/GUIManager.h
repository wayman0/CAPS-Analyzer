class GUIManager
{
    public:
        GUIManager();
        virtual ~GUIManager();

        virtual void updateProgressBar(int value)               = 0;
        virtual void updateProgressText(const char* updateName) = 0;
        virtual void errorMessage(const char* errMess)          = 0;
        virtual void displayMessage(const char* mess)           = 0;
        virtual bool addDataMessage(const char* errMess)        = 0;
        virtual bool replaceDataChain(const char* mess)         = 0;

        virtual void addAssociation()                           = 0;
        virtual void setAssociation(association* newAssoc)      = 0;

        virtual void selectFileName(bool read) = 0;

        virtual void emitReadDataSets(FILETYPE* dataTypes, int* numTypes) = 0;
        virtual void emitSelectSlices() = 0;
        virtual void emitSelectEnergies() = 0;
        void readData(int numTypes, FILETYPE dataTypes[]);
        void openFile();

        virtual void emitSaveDataSets() = 0;
        void writeData(int numTypes, FILETYPE dataTypes[]);
        void saveFile();

        void createControlData(FILETYPE dataType, bool complete);

        void setPixelizerAttr();
        int pixelize();
        bool pixelize(FILETYPE inputDataType, FILETYPE pixelDataType);

		bool handleMissingTransformer();
        void setTransformerAttr();
        int transform();
        bool transform(FILETYPE pixelDataType, FILETYPE transDataType);

        int invert();
        bool invert(FILETYPE inverseType, FILETYPE almType);

        void setAnalyzerAttr();
        void analyze();

        virtual void selectPixelizer() = 0;
        virtual void configurePixelizer(PIXELSCHEME scheme) = 0;

        virtual void selectTransformer() = 0;
        virtual void configureTransformer(TRANSFORMERSCHEME scheme) = 0;

        virtual void selectAnalzyer() = 0;
        virtual void configureAnalyzer() = 0;

        virtual void configureDisplay(FILETYPE dataType) = 0;
        virtual void displayGraph(ASSOCIATEDSPECTRUM graph) = 0;
        virtual void displayMap(ASSOCIATEDMAP map) = 0;

    protected:
        association               *s_association;
        std::vector<association*> *associationVector;
        FILETYPE                   selectedDataType;
        GENERICTYPE                selectedDataStream;
        FORMAT                     dataFormat;
        std::string                fileName;
        OBSERVATORY                dataSource;

        associationSelectDialogParent *assocDlg;
        controlDataDialogParent       *ctrlDlg;
        dataSelectDialogParent        *dataSelectDlg;
        energyDialogParent            *energyDlg;
        multipleSelectionDialogParent *multSelDlg;
        pixelizerDialogParent         *pixSelectDlg;
        healpixDialogParent           *healpixDlg;
        transformerDialogParent       *transSelectDlg;
        rshtDialogParent              *rshtDlg;
        analyzerDialogParent          *analSelectDlg;
        spectrumDialogParent          *specDlg;
};
#endif


