void ShellWindow::updateProgressBar(int value)
{
	const int barWidth = 50;

    (*output) << "\r[";
    int pos = value * barWidth / 100;

    for (int i = 0; i < barWidth; i += 1)
	{
        if (i < pos)
			(*output) << "=";
        else if (i == pos)
			(*output) << ">";
        else
			(*output) << " ";
    }

    (*output) << "] " << value << "%";
    output->flush();
}

