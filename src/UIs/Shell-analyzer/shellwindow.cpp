void ShellWindow::execute()
{
	printMenu();

	for(int choice = getChoice(); choice != 0; choice = getChoice())
	{
		if(choice == 1)
		{
			static_cast<controlDataDialog*>(ctrlDlg)->execute();
		}
		else if(choice == 2)
			(*output) << "Open File\n";
		else if(choice == 3)
			(*output) << "Save File\n";
		else if(choice == 4)
		{
			(*output) << "Pixelize\n";

		}
		else if(choice == 5)
			(*output) << "Transform\n";
		else if(choice == 6)
			(*output) << "Analyzer\n";
		else
		{
			clearInput();
			printInvalidChoice();
		}

		printMenu();
	}
}

void ShellWindow::printMenu()
{
	(*output) << "MENU CHOICES: \n";
	(*output) << "\t0. Exit\n"
			  << "\t1. Create Control Data\n"
			  << "\t2. Open File\n"
			  << "\t3. Save File\n"
			  << "\t4. Pixelize\n"
			  << "\t5. Transform\n"
			  << "\t6. Analyze\n";
}

int ShellWindow::getChoice()
{
	int choice = 0;

	if((*input) >> choice)
		return choice;

	do
	{
		clearInput();
		printInvalidChoice();
	}
	while(! ((*input) >> choice));

	return choice;
}

void ShellWindow::clearInput()
{
	input->clear();
	input->ignore(std::numeric_limits<std::streamsize>::max(), '\n');
}

void ShellWindow::printInvalidChoice()
{
	(*output) << "Invalid choice please choose again.\n";
	printMenu();
}

