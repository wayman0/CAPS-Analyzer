void ShellWindow::updateProgressBar(int value)
{
	const int barWidth = 50;

	(*output) << "\r\033[?25l" << "[";

	int pos = value * barWidth / 100;
    for (int i = 0; i < barWidth; i += 1)
	{
        if (i < pos)
			(*output) << "\033[32m=";
        else if (i == pos)
			(*output) << "\033[0m>";
        else
			(*output) << " ";
    }

    (*output) << "\033[0m" << "] " << value << "%";
    output->flush();

	if(value == 100)
		(*output) << "\033[?25h\n";
}

