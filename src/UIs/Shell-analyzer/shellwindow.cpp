bool ShellWindow::addDataMessage(const char* errMess)
{
	char add = 'n';
	do
	{
		clearInput();
		(*output) << "\033[33m" << errMess << "\033[0m\n";
		(*output) << "Create: c, Open: o, No: n" << "\t";
	} while(	!((*input)>>add)
				|| !(   add == 'C' || add == 'c'
					||	add == 'O' || add == 'o'
					|| 	add == 'N' || add == 'n'));

	if(add == 'c' || add == 'C')
		static_cast<controlDataDialog*>(ctrlDlg)->execute();
	else if(add == 'o' || add == 'O')
		(*output) << "OPEN FILE\n";
	else
		return false;

	return true;
}

bool ShellWindow::replaceDataChain(const char* mess)
{
	char add = 'n';
	do
	{
		clearInput();
		(*output) << "\033[33m" << mess << "(Y|N)" << "\033[0m";
	} while(	!((*input)>>add)
				|| !(   add == 'Y' || add == 'y'
				|| 		add == 'N' || add == 'n'));

	return add == 'y' || add == 'Y' ? true : false;
}

void ShellWindow::printAssocStatus()
{
	clearScreen();

	(*output) << std::left;

	for(fileType ft = FILETYPE::InputData; ft != FILETYPE::FILETYPE_LIMIT; ft = static_cast<FILETYPE>(static_cast<int>(ft)+1))
	{
		if(s_association->exists(ft))
		{
			(*output) << "\033[32m";
			(*output) << std::setw(70) << dataTypeNames[static_cast<int>(ft)] << "\t\tdoes    exist.";
			(*output) << "\033[0m\n";
		}
		else
		{
			if(ft != FILETYPE::MAP_LIMIT && ft != FILETYPE::GRAPH_LIMIT && ft != FILETYPE::TRANSFORM_LIMIT)
			{
				(*output) << "\033[31m";
				(*output) << std::setw(70) << dataTypeNames[static_cast<int>(ft)] << "\t\tdoesn't exist.";
				(*output) << "\033[0m\n";
			}
		}
	}

	(*output) << "Press any key to continue to main menu.\n";
	clearInput();
	input->get();
}

void ShellWindow::execute()
{
	printMenu();

	for(int choice = getChoice(); choice != 0; choice = getChoice())
	{
		if(choice == 1)
			static_cast<controlDataDialog*>(ctrlDlg)->execute();
		else if(choice == 2)
			openFile();
		else if(choice == 3)
			saveFile();
		else if(choice == 4)
			selectPixelizer(); //static_cast<healpixDialog*>(healpixDlg)->execute();
		else if(choice == 5)
			selectTransformer(); //static_cast<rshtDialog*>(rshtDlg)->execute();
		else if(choice == 6)
			selectAnalzyer(); //static_cast<spectrumDialog*>(specDlg)->execute();
		else if(choice == 7)
			(*output) << "Option currently unavailable.\n";//static_cast<mapSelectDialog*>(mapSelectDlg)->execute();
		else if(choice == 8)
			(*output) << "Option currently unavailable.\n";//static_cast<graphSelectDialog*>(graphSelectDlg)->execute();
		else if(choice == 9)
			printAssocStatus();
		else if(choice == 10)
			addAssociation();
		else if(choice == 11)
			static_cast<associationSelectDialog*>(assocDlg)->execute();
		else
		{
			clearInput();
			printInvalidChoice();
		}

		clearScreen();
		printMenu();
	}
}

