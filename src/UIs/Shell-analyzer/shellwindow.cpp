bool ShellWindow::selectFileName(bool read)
{
	rl_bind_key('\t', rl_complete);
	rl_completion_suppress_append = 0;

	if(read)
	{
		std::filesystem::path inputFile = "";
		do
		{
			char* inFl = readline("Enter the filename to read data from.\n");
			add_history(inFl);

			if(!inFl || inFl[0] == '\0')
			{
				errorMessage("Quitting reading file.\n");
				return false;
			}

			// we have to check for whitespace because auto complete adds a trailing space!
			string file = string(inFl);
			size_t trailWS = file.find_last_not_of(" \t\n\r\f\v");

			if (trailWS != std::string::npos)
				file.erase(trailWS + 1);

			inputFile = file;
			if(!std::filesystem::exists(inputFile))
			{
				errorMessage(string("File: " + inputFile.string() + " does not exist.\n").c_str());
			}
		}while(! std::filesystem::exists(inputFile));


		// parse the file type ie csv fits hdf5
		std::string ext = inputFile.extension();

		if(ext == ".fit" || ext == ".fits" || ext == ".fts")
			dataFormat = Fits;
		else if(ext == ".csv" || ext == ".txt")
			dataFormat = CSV;
		else if(ext == ".hdf5" || ext == ".h5")
			dataFormat = HDF5;
		else
		{
			errorMessage(string("Unknown file format: " + ext + " quiting open file operation.\n").c_str());
			return false;
		}

		fileName = inputFile.string();

		// get the observatory;
		std::string obsNames = "";
		int obsInd = 1;// 0 is unknown we dont' want that to be an option
		for(obsInd = 1; obsInd < static_cast<int>(OBSERVATORY::OBSERVATORY_LIMIT); obsInd += 1)
			obsNames += "\t" + std::to_string(obsInd) + ". " + observatoryNames[obsInd] + "\n";

		do
		{
			clearInput();

			(*output) << "Enter the observatory the data is from.\n";
			(*output) << obsNames;
		}while(	!((*input)>>obsInd)
				|| obsInd < 1
				|| obsInd >= static_cast<int>(OBSERVATORY_LIMIT));

		dataSource = static_cast<OBSERVATORY>(obsInd);
	}
	else
	{
		std::filesystem::path outFile = "";
		//do
		//{
			char* outFl = readline("Enter the filename to write data to.\n");
			add_history(outFl);

			if(!outFl || outFl[0] == '\0')
			{
				errorMessage("Quitting writing file.\n");
				return false;
			}

			// we have to check for whitespace because auto complete adds a trailing space!
			string file = string(outFl);
			size_t trailWS = file.find_last_not_of(" \t\n\r\f\v");

			if (trailWS != std::string::npos)
				file.erase(trailWS + 1);

			outFile = file;
			if(std::filesystem::exists(outFile))
				displayMessage(string("File: " + outFile.string() + " already exists.\n").c_str());

		//}while(std::filesystem::exists(outFile));


		// parse the file type ie csv fits hdf5
		std::string ext = outFile.extension();

		if(ext == ".fit" || ext == ".fits" || ext == ".fts")
			dataFormat = Fits;
		else if(ext == ".csv" || ext == ".txt")
			dataFormat = CSV;
		else if(ext == ".hdf5" || ext == ".h5")
			dataFormat = HDF5;
		else
		{
			errorMessage(string("Unknown file format: " + ext + " quiting open file operation.\n").c_str());
			return false;
		}

		fileName = outFile.string();
	}

	return true;
}

