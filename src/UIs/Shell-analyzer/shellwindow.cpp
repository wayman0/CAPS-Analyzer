int ShellWindow::getChoice()
{
	int choice = 0;

	if((*input) >> choice)
		return choice;

	do
	{
		clearInput();
		printInvalidChoice();
	}
	while(! ((*input) >> choice));

	return choice;
}

void ShellWindow::printInvalidChoice()
{
	(*output) << "Invalid choice please choose again.\n";
	printMenu();
}

